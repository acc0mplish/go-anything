package layout

import (
	"fmt"
	"strings"
)

// versionPattern is the shape a tag or VERSION must have before it reaches -ldflags or a file name.
// Git allows $, (, ` and ; in ref names, so the value is checked, never trusted.
const versionPattern = `^v[0-9A-Za-z._+-]+$`

// project is the archive prefix: the last module path element, skipping a /vN major suffix.
func (p *LayoutPlan) project() string { return binName(p.Module) }

// pkgArg is the package argument for go build, relative to the module root.
func pkgArg(m MainPkg) string {
	if m.Dir == "." {
		return "."
	}
	return "./" + m.Dir
}

// runnerFor picks a GitHub-hosted runner. Without cgo every target cross-builds on Linux.
// With cgo the build must run natively on the target platform.
func runnerFor(t Target, cgo bool) string {
	if !cgo {
		return "ubuntu-latest"
	}
	switch t.String() {
	case "linux/arm64":
		return "ubuntu-24.04-arm"
	case "darwin/arm64":
		return "macos-latest"
	case "darwin/amd64":
		return "macos-13"
	case "windows/amd64":
		return "windows-latest"
	}
	return "ubuntu-latest"
}

// indent prefixes every non-empty line of s.
func indent(s, prefix string) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	for i, l := range lines {
		if l != "" {
			lines[i] = prefix + l
		}
	}
	return strings.Join(lines, "\n") + "\n"
}

// buildStepScript is the run: body of the workflow's build step. It reads only environment
// variables (GOOS, GOARCH, VERSION); no ${{ }} expression is expanded inside it.
func buildStepScript(p *LayoutPlan) string {
	var b strings.Builder
	b.WriteString("set -euo pipefail\n")
	fmt.Fprintf(&b, "if [[ ! \"$VERSION\" =~ %s ]]; then\n", versionPattern)
	b.WriteString("  echo \"refusing to build: tag name is not a plain version\" >&2\n  exit 1\nfi\n")
	b.WriteString("ext=\"\"\nif [[ \"$GOOS\" == \"windows\" ]]; then ext=\".exe\"; fi\n")
	fmt.Fprintf(&b, "name=\"%s_${VERSION}_${GOOS}_${GOARCH}\"\n", p.project())
	b.WriteString("mkdir -p \"dist/$name\"\n")
	for _, m := range p.Mains {
		fmt.Fprintf(&b, "go build -trimpath -ldflags \"-s -w -X main.version=$VERSION\" -o \"dist/$name/%s$ext\" \"%s\"\n", m.BinName, pkgArg(m))
	}
	b.WriteString("for f in LICENSE LICENSE.md LICENSE.txt README.md; do\n  if [[ -f \"$f\" ]]; then cp \"$f\" \"dist/$name/\"; fi\ndone\n")
	b.WriteString("cd dist\n")
	b.WriteString("if [[ \"$GOOS\" == \"windows\" ]]; then\n")
	b.WriteString("  if command -v zip >/dev/null 2>&1; then zip -q -r \"$name.zip\" \"$name\"; else 7z a -tzip -bd \"$name.zip\" \"$name\" >/dev/null; fi\n")
	b.WriteString("else\n  tar -czf \"$name.tar.gz\" \"$name\"\nfi\n")
	b.WriteString("rm -rf \"$name\"\n")
	return b.String()
}

// releaseStepScript is the run: body of the release job. It needs GH_TOKEN, VERSION and
// GITHUB_REPOSITORY in the environment and the gh CLI that GitHub-hosted runners ship.
func releaseStepScript() string {
	var b strings.Builder
	b.WriteString("set -euo pipefail\n")
	fmt.Fprintf(&b, "if [[ ! \"$VERSION\" =~ %s ]]; then\n", versionPattern)
	b.WriteString("  echo \"refusing to release: tag name is not a plain version\" >&2\n  exit 1\nfi\n")
	b.WriteString("cd dist\nshopt -s nullglob\nfiles=(*.tar.gz *.zip)\n")
	b.WriteString("if (( ${#files[@]} == 0 )); then echo \"no archives to release\" >&2; exit 1; fi\n")
	b.WriteString("sha256sum -- \"${files[@]}\" > SHA256SUMS\n")
	b.WriteString("gh release create \"$VERSION\" \"${files[@]}\" SHA256SUMS --repo \"$GITHUB_REPOSITORY\" --title \"$VERSION\" --generate-notes --verify-tag\n")
	return b.String()
}

func renderWorkflow(p *LayoutPlan) string {
	var b strings.Builder
	b.WriteString("# Generated by `go-anything package`. Review it before the first release.\n")
	if p.UsesCgo {
		b.WriteString("# The module uses cgo, so each target builds natively on its own runner with CGO_ENABLED=1.\n")
	} else {
		b.WriteString("# Every target cross-builds on one Linux runner with CGO_ENABLED=0.\n")
	}
	b.WriteString("# Archives and SHA256SUMS go to the GitHub release of the pushed v* tag.\n")
	b.WriteString("# Untrusted values (the tag name) reach run: steps only through env and are checked there.\n")
	b.WriteString(`name: release

on:
  push:
    tags:
      - "v*"

permissions:
  contents: read

defaults:
  run:
    shell: bash

jobs:
  build:
    name: build ${{ matrix.goos }}/${{ matrix.goarch }}
    runs-on: ${{ matrix.runner }}
    strategy:
      fail-fast: true
      matrix:
        include:
`)
	for _, t := range p.Targets {
		fmt.Fprintf(&b, "          - goos: %s\n            goarch: %s\n            runner: %s\n", t.GOOS, t.GOARCH, runnerFor(t, p.UsesCgo))
	}
	cgo := "0"
	if p.UsesCgo {
		cgo = "1"
	}
	b.WriteString(`    steps:
      - name: checkout
        uses: actions/checkout@v4
        with:
          persist-credentials: false
      - name: set up Go
        uses: actions/setup-go@v5
        with:
          go-version-file: go.mod
          cache: false
      - name: build and archive
        env:
          GOOS: ${{ matrix.goos }}
          GOARCH: ${{ matrix.goarch }}
`)
	fmt.Fprintf(&b, "          CGO_ENABLED: \"%s\"\n", cgo)
	b.WriteString("          VERSION: ${{ github.ref_name }}\n")
	b.WriteString("        run: |\n")
	b.WriteString(indent(buildStepScript(p), "          "))
	b.WriteString(`      - name: upload archive
        uses: actions/upload-artifact@v4
        with:
          name: archive-${{ matrix.goos }}-${{ matrix.goarch }}
          path: |
            dist/*.tar.gz
            dist/*.zip
          if-no-files-found: error

  release:
    needs: build
    runs-on: ubuntu-latest
    permissions:
      contents: write
    steps:
      - name: download archives
        uses: actions/download-artifact@v4
        with:
          pattern: archive-*
          path: dist
          merge-multiple: true
      - name: checksums and release
        env:
          GH_TOKEN: ${{ github.token }}
          VERSION: ${{ github.ref_name }}
        run: |
`)
	b.WriteString(indent(releaseStepScript(), "          "))
	return b.String()
}

func renderBuildScript(p *LayoutPlan) string {
	var b strings.Builder
	b.WriteString("#!/usr/bin/env bash\n")
	b.WriteString("# Generated by `go-anything package`. Builds every main package for every target into dist/,\n")
	b.WriteString("# the same way .github/workflows/release.yml does in CI. It publishes nothing.\n")
	b.WriteString("#   scripts/build-all.sh\n")
	b.WriteString("#   VERSION=v1.2.3 TARGETS=\"linux/amd64 darwin/arm64\" scripts/build-all.sh\n")
	b.WriteString("set -euo pipefail\n")
	b.WriteString("cd \"$(dirname \"$0\")/..\"\n\n")
	b.WriteString("VERSION=\"${VERSION:-$(git describe --tags --always --dirty 2>/dev/null || echo dev)}\"\n")
	b.WriteString("if [[ ! \"$VERSION\" =~ ^[0-9A-Za-z._+-]+$ ]]; then\n  echo \"VERSION has characters that do not belong in a file name\" >&2\n  exit 1\nfi\n")
	var ts []string
	for _, t := range p.Targets {
		ts = append(ts, t.String())
	}
	fmt.Fprintf(&b, "TARGETS=\"${TARGETS:-%s}\"\n", strings.Join(ts, " "))
	if p.UsesCgo {
		b.WriteString("# The module uses cgo: only the host target is planned and CGO_ENABLED is left as the toolchain sets it.\n")
	} else {
		b.WriteString("export CGO_ENABLED=0\n")
	}
	b.WriteString(`
if command -v sha256sum >/dev/null 2>&1; then sum=(sha256sum); else sum=(shasum -a 256); fi
mkdir -p dist
archives=()
for target in $TARGETS; do
  if [[ ! "$target" =~ ^[a-z0-9]+/[a-z0-9]+$ ]]; then echo "bad target: $target" >&2; exit 1; fi
  goos="${target%/*}"
  goarch="${target#*/}"
  ext=""
  if [[ "$goos" == "windows" ]]; then ext=".exe"; fi
`)
	fmt.Fprintf(&b, "  name=\"%s_${VERSION}_${goos}_${goarch}\"\n", p.project())
	b.WriteString("  rm -rf \"dist/$name\" \"dist/$name.tar.gz\" \"dist/$name.zip\"\n")
	b.WriteString("  mkdir -p \"dist/$name\"\n")
	b.WriteString("  echo \"building $target\"\n")
	for _, m := range p.Mains {
		fmt.Fprintf(&b, "  GOOS=\"$goos\" GOARCH=\"$goarch\" go build -trimpath -ldflags \"-s -w -X main.version=$VERSION\" -o \"dist/$name/%s$ext\" \"%s\"\n", m.BinName, pkgArg(m))
	}
	b.WriteString(`  for f in LICENSE LICENSE.md LICENSE.txt README.md; do
    if [[ -f "$f" ]]; then cp "$f" "dist/$name/"; fi
  done
  if [[ "$goos" == "windows" ]]; then
    if command -v zip >/dev/null 2>&1; then
      (cd dist && zip -q -r "$name.zip" "$name")
    elif command -v python3 >/dev/null 2>&1; then
      (cd dist && python3 -m zipfile -c "$name.zip" "$name")
    else
      echo "need zip or python3 to archive $target" >&2
      exit 1
    fi
    archives+=("$name.zip")
  else
    (cd dist && tar -czf "$name.tar.gz" "$name")
    archives+=("$name.tar.gz")
  fi
  rm -rf "dist/$name"
done
if (( ${#archives[@]} == 0 )); then echo "no targets" >&2; exit 1; fi
(cd dist && "${sum[@]}" -- "${archives[@]}" > SHA256SUMS)
echo "wrote ${#archives[@]} archives and dist/SHA256SUMS"
`)
	return b.String()
}

func renderInstall(p *LayoutPlan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Installing %s\n\n", p.project())
	b.WriteString("## With the Go toolchain\n\n")
	if p.GoVersion != "" {
		fmt.Fprintf(&b, "Needs Go %s or newer (from go.mod). ", p.GoVersion)
	}
	b.WriteString("The binary lands in `$(go env GOBIN)`, or `$(go env GOPATH)/bin` when GOBIN is unset.\n\n```sh\n")
	for _, m := range p.Mains {
		fmt.Fprintf(&b, "go install %s@latest\n", m.ImportPath)
	}
	b.WriteString("```\n\nReplace `@latest` with a tag such as `@v1.2.3` to pin a release.\n")
	if p.UsesCgo {
		b.WriteString("\nThis module uses cgo, so `go install` also needs a C compiler (gcc or clang) on your machine.\n")
	}

	b.WriteString("\n## Prebuilt binaries\n\n")
	releases := "the project's releases page"
	if strings.HasPrefix(p.Module, "github.com/") {
		if parts := strings.Split(p.Module, "/"); len(parts) >= 3 {
			releases = fmt.Sprintf("https://%s/%s/%s/releases", parts[0], parts[1], parts[2])
		}
	}
	fmt.Fprintf(&b, "Each release on %s has one archive per platform and a `SHA256SUMS` file.\n\n", releases)
	b.WriteString("| Platform | Archive |\n|---|---|\n")
	for _, t := range p.Targets {
		ext := "tar.gz"
		if t.GOOS == "windows" {
			ext = "zip"
		}
		fmt.Fprintf(&b, "| %s | `%s_<version>_%s_%s.%s` |\n", t, p.project(), t.GOOS, t.GOARCH, ext)
	}
	b.WriteString("\n1. Download the archive for your platform and `SHA256SUMS`.\n")
	b.WriteString("2. Check it: `sha256sum --ignore-missing -c SHA256SUMS` (macOS: `shasum -a 256 --ignore-missing -c SHA256SUMS`).\n")
	b.WriteString("3. Unpack it and put the binary on your PATH.\n")
	if p.UsesCgo {
		fmt.Fprintf(&b, "\nOnly %s is built. The module uses cgo (%s), and cgo does not cross-compile with CGO_ENABLED=0. Other platforms need `go install` with a local C compiler, or a native build runner per platform.\n",
			strings.Join(targetStrings(p.Targets), ", "), strings.Join(p.CgoFiles, ", "))
	}
	b.WriteString("\n## Building every platform locally\n\n```sh\nscripts/build-all.sh\n```\n\nArchives and `SHA256SUMS` go to `dist/`.\n")
	return b.String()
}

func targetStrings(ts []Target) []string {
	out := make([]string, len(ts))
	for i, t := range ts {
		out[i] = t.String()
	}
	return out
}
