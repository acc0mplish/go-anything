const (
	origAlias = "gaorig"
	rewAlias  = "garew"
	// FuncsFile holds the header, re-exports and one wrapper per function.
	FuncsFile = "shadow.go"
	// RuntimeFile holds the mode switch, the comparison and the mismatch log.
	RuntimeFile = "shadow_runtime.go"
)

// imports gives every package a file-unique name in the generated wrapper file.
type imports struct {
	byPath map[string]string
	taken  map[string]string // name -> path
	orig   *types.Package
	rew    *types.Package
}

func newImports(orig, rew *types.Package, topNames []string) *imports {
	im := &imports{byPath: map[string]string{}, taken: map[string]string{}, orig: orig, rew: rew}
	im.byPath[orig.Path()] = origAlias
	im.taken[origAlias] = orig.Path()
	im.byPath[rew.Path()] = rewAlias
	im.taken[rewAlias] = rew.Path()
	for _, n := range topNames { // a file-scope import may not share a name with a package-level name
		im.taken[n] = ""
	}
	return im
}

func (im *imports) qualify(p *types.Package) string {
	if name, ok := im.byPath[p.Path()]; ok {
		return name
	}
	base := p.Name()
	name := base
	for i := 2; ; i++ {
		if _, used := im.taken[name]; !used {
			break
		}
		name = base + strconv.Itoa(i)
	}
	im.byPath[p.Path()] = name
	im.taken[name] = p.Path()
	return name
}

func (im *imports) typ(t types.Type) string { return types.TypeString(t, im.qualify) }

func (im *imports) specs() []string {
	paths := make([]string, 0, len(im.byPath))
	for p := range im.byPath {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	out := make([]string, 0, len(paths))
	for _, p := range paths {
		if name := im.byPath[p]; name == path.Base(p) {
			out = append(out, strconv.Quote(p))
		} else {
			out = append(out, name+" "+strconv.Quote(p))
		}
	}
	return out
}

// wrapper is the per-function row of the template table.
type wrapper struct {
	Name        string
	Params      string // parameter list of the wrapper
	Results     string // result list of the wrapper
	Call        string // arguments as passed to the original and the rewrite
	Args        string // arguments as values for the log
	NRes        int
	OrigVars    string
	RewVars     string
	ErrMask     string
	Eager       bool // render the arguments before the calls, since a call may change them
	Passthrough bool
}

func makeWrapper(f Func, im *imports, eager, passthrough bool) wrapper {
	w := wrapper{Name: f.Name, NRes: len(f.Results), Eager: eager, Passthrough: passthrough}
	var params, call, args []string
	for i, p := range f.Params {
		if f.Variadic && i == len(f.Params)-1 {
			elem := p.Type.(*types.Slice).Elem()
			params = append(params, p.Name+" ..."+im.typ(elem))
			call = append(call, p.Name+"...")
		} else {
			params = append(params, p.Name+" "+im.typ(p.Type))
			call = append(call, p.Name)
		}
		args = append(args, p.Name)
	}
	var res, ov, rv, mask []string
	for i, r := range f.Results {
		res = append(res, im.typ(r.Type))
		ov = append(ov, "gaO"+strconv.Itoa(i))
		rv = append(rv, "gaR"+strconv.Itoa(i))
		mask = append(mask, strconv.FormatBool(r.IsError))
	}
	w.Params = strings.Join(params, ", ")
	w.Call = strings.Join(call, ", ")
	w.Args = strings.Join(args, ", ")
	switch len(res) {
	case 0:
	case 1:
		w.Results = res[0]
	default:
		w.Results = "(" + strings.Join(res, ", ") + ")"
	}
	w.OrigVars = strings.Join(ov, ", ")
	w.RewVars = strings.Join(rv, ", ")
	w.ErrMask = "[]bool{" + strings.Join(mask, ", ") + "}"
	return w
}

