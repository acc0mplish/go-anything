var runtimeTemplate = template.Must(template.New("runtime").Parse(`// Code generated by go-anything shadow gen. DO NOT EDIT.

package {{.Package}}

import (
	"encoding/json"
	"fmt"
	"os"
	"reflect"
	"strings"
	"sync"
	"time"
)

const (
	gaModeOld = iota
	gaModeShadow
	gaModeNew
)

const (
	gaModeEnv   = "{{.EnvVar}}"
	gaLogEnv    = "GA_SHADOW_LOG"
	gaRedactEnv = "GA_SHADOW_REDACT"
	gaMaxRepr   = 4096
)

var (
	gaWarnOnce sync.Once
	gaLogMu    sync.Mutex // serializes every write to the mismatch log
)

// gaMode reads the mode on every call, so it can be switched while the program runs.
func gaMode() int {
	switch v := os.Getenv(gaModeEnv); v {
	case "", "old":
		return gaModeOld
	case "shadow":
		return gaModeShadow
	case "new":
		return gaModeNew
	default:
		gaWarnOnce.Do(func() {
			fmt.Fprintf(os.Stderr, "shadow: %s=%q is not old, shadow or new; using old\n", gaModeEnv, v)
		})
		return gaModeOld
	}
}

func gaRepr(v any) string {
	s := fmt.Sprintf("%#v", v)
	if len(s) > gaMaxRepr {
		s = s[:gaMaxRepr] + "...(truncated)"
	}
	return s
}

// gaArgsNow renders the arguments before either call, for functions that may change them.
func gaArgsNow(args ...any) func() string {
	s := gaArgsRepr(args)
	return func() string { return s }
}

// gaArgsLater renders the arguments only when there is a mismatch to report.
func gaArgsLater(args ...any) func() string {
	return func() string { return gaArgsRepr(args) }
}

// gaArgsRepr renders the arguments as a Go argument list, for example 2, "x", []int{1}.
func gaArgsRepr(args []any) string {
	parts := make([]string, len(args))
	for i, a := range args {
		parts[i] = gaRepr(a)
	}
	return strings.Join(parts, ", ")
}

// gaCompare runs the rewrite and logs a disagreement with the original's results. Nothing the rewrite
// does, including a panic, reaches the caller.
func gaCompare(name string, args func() string, orig []any, errMask []bool, rewrite func() []any) {
	defer func() {
		if p := recover(); p != nil {
			gaReport(name, args, gaResults(orig, errMask), []string{fmt.Sprintf("shadow comparison panicked: %v", p)})
		}
	}()
	rew, panicked, p := gaRun(rewrite)
	if panicked {
		gaReport(name, args, gaResults(orig, errMask), []string{fmt.Sprintf("panic: %v", p)})
		return
	}
	if gaEqual(orig, rew, errMask) {
		return
	}
	gaReport(name, args, gaResults(orig, errMask), gaResults(rew, errMask))
}

func gaRun(f func() []any) (res []any, panicked bool, p any) {
	panicked = true
	defer func() {
		if panicked {
			p = recover()
		}
	}()
	res = f()
	panicked = false
	return res, false, nil
}

// gaEqual compares errors by nil-ness and Error() text and everything else with reflect.DeepEqual.
func gaEqual(a, b []any, errMask []bool) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if errMask[i] {
			ea, _ := a[i].(error)
			eb, _ := b[i].(error)
			if (ea == nil) != (eb == nil) {
				return false
			}
			if ea != nil && ea.Error() != eb.Error() {
				return false
			}
			continue
		}
		if !reflect.DeepEqual(a[i], b[i]) {
			return false
		}
	}
	return true
}

func gaResults(vals []any, errMask []bool) []string {
	out := make([]string, len(vals))
	for i, v := range vals {
		if errMask[i] {
			if e, _ := v.(error); e != nil {
				out[i] = "error: " + e.Error()
			} else {
				out[i] = "error: nil"
			}
			continue
		}
		out[i] = gaRepr(v)
	}
	return out
}

type gaMismatch struct {
	Func     string   ` + "`json:\"func\"`" + `
	ArgsRepr string   ` + "`json:\"args_repr\"`" + `
	Original []string ` + "`json:\"original\"`" + `
	Rewrite  []string ` + "`json:\"rewrite\"`" + `
	Time     string   ` + "`json:\"time\"`" + `
}

func gaReport(name string, args func() string, orig, rew []string) {
	m := gaMismatch{Func: name, Original: orig, Rewrite: rew, Time: time.Now().UTC().Format(time.RFC3339Nano)}
	if os.Getenv(gaRedactEnv) == "1" {
		m.ArgsRepr, m.Original, m.Rewrite = "[redacted]", []string{"[redacted]"}, []string{"[redacted]"}
	} else {
		m.ArgsRepr = args()
	}
	line, err := json.Marshal(m)
	if err != nil {
		line = []byte(fmt.Sprintf("{\"func\":%q,\"error\":%q}", name, err.Error()))
	}
	line = append(line, '\n')
	gaLogMu.Lock()
	defer gaLogMu.Unlock()
	path := os.Getenv(gaLogEnv)
	if path == "" {
		_, _ = os.Stderr.Write(line)
		return
	}
	f, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o600)
	if err != nil {
		fmt.Fprintf(os.Stderr, "shadow: cannot open %s: %v\n", gaLogEnv, err)
		_, _ = os.Stderr.Write(line)
		return
	}
	_, werr := f.Write(line)
	cerr := f.Close()
	if werr != nil || cerr != nil {
		fmt.Fprintf(os.Stderr, "shadow: write %s: %v %v\n", gaLogEnv, werr, cerr)
		_, _ = os.Stderr.Write(line)
	}
}
`))

// render returns the formatted source of both generated files.
func render(a *analysis, original, rewrite string) (funcs, runtime []byte, err error) {
	var top []string
	for _, tn := range a.types {
		top = append(top, tn.Name())
	}
	for _, c := range a.consts {
		top = append(top, c.Name())
	}
	all := append(append([]Func{}, a.funcs...), a.passFuncs...)
	sort.Slice(all, func(i, j int) bool { return all[i].Name < all[j].Name })
	for _, f := range all {
		top = append(top, f.Name)
	}
	im := newImports(a.orig, a.rew, top)
	shadowed := map[string]bool{}
	for _, f := range a.funcs {
		shadowed[f.Name] = true
	}
	var ws []wrapper
	for _, f := range all {
		ws = append(ws, makeWrapper(f, im, a.risky[f.Name], !shadowed[f.Name]))
	}
	if len(a.funcs) == 0 { // the rewrite import would be unused
		delete(im.byPath, a.rew.Path())
	}
	data := map[string]any{
		"Package":     a.report.Package,
		"Original":    original,
		"Rewrite":     rewrite,
		"EnvVar":      a.report.EnvVar,
		"Limits":      Limits,
		"NotShadowed": a.report.NotShadowed,
		"Risks":       a.report.Risks,
		"Imports":     im.specs(),
		"Types":       top[:len(a.types)],
		"Consts":      top[len(a.types) : len(a.types)+len(a.consts)],
		"Wrappers":    ws,
	}
	if funcs, err = execFormat(funcsTemplate, data); err != nil {
		return nil, nil, err
	}
	if runtime, err = execFormat(runtimeTemplate, data); err != nil {
		return nil, nil, err
	}
	return funcs, runtime, nil
}

func execFormat(t *template.Template, data any) ([]byte, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("shadow gen: render %s: %w", t.Name(), err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("shadow gen: generated %s does not parse: %w\n%s", t.Name(), err, buf.String())
	}
	return src, nil
}
