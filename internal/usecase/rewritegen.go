// CLICasesTest renders units/<unit>/cases_test.go for a command-line unit.
func CLICasesTest(unit string, cases []domain.AppCase, opt domain.CompareOptions) ([]byte, error) {
	if err := ValidUnitName(unit); err != nil {
		return nil, err
	}
	type row struct {
		Name, Args, Stdin, Stdout, Stderr, Unstable string
		Code                                        int
	}
	var rows []row
	for _, c := range cases {
		quoted := make([]string, 0, len(c.Argv))
		for _, a := range c.Argv {
			quoted = append(quoted, strconv.Quote(a))
		}
		rows = append(rows, row{
			Name:     strconv.Quote(c.Name),
			Args:     strings.Join(quoted, ", "),
			Stdin:    strconv.Quote(c.Stdin),
			Code:     c.ExitCode,
			Stdout:   strconv.Quote(c.Stdout),
			Stderr:   strconv.Quote(c.Stderr),
			Unstable: quotedList(c.Unstable),
		})
	}
	t, err := template.New("cli-cases").Parse(cliCasesTestTemplate)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, struct {
		Unit                string
		JSONBody, Tolerance string
		Normalize           string
		Cases               []row
	}{unit, strconv.FormatBool(opt.JSONBody), strconv.FormatFloat(opt.FloatTolerance, 'g', -1, 64), quotedList(opt.Normalize), rows}); err != nil {
		return nil, fmt.Errorf("wire: render cli cases test: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("wire: cli cases test does not format: %w", err)
	}
	return formatted, nil
}

// AgentPromptCLI is the brief for a command-line unit. Same clean-room rule: recorded behavior only.
func AgentPromptCLI(unit string, cases []domain.AppCase, previousFailure string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Write the Go file units/%[1]s/rewrite.go for the command %[1]q of a command-line program.\n\n", unit)
	b.WriteString("Contract:\n")
	fmt.Fprintf(&b, "- package %s, with exactly this function:\n", unit)
	b.WriteString("  func Handle(args []string, stdin io.Reader, stdout, stderr io.Writer) int\n")
	b.WriteString("- args is the whole argument list with the command word first, exactly as the original receives it.\n")
	b.WriteString("- Write the program's output to stdout and stderr exactly as the recorded behavior shows, and return the exit code.\n")
	b.WriteString("- Replace the whole file. Do not touch any other file. Use only the standard library.\n")
	b.WriteString("- Do not panic and do not leave placeholders.\n\n")
	b.WriteString("Clean room: you may use ONLY the recorded behavior below. Do not look for, open or copy the\n")
	b.WriteString("original program's source. Implement what the cases show, in general, not just these inputs.\n\n")
	b.WriteString("Recorded behavior (arguments, stdin -> exit code, stdout, stderr of the original):\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "- args=%q", c.Argv)
		if c.Stdin != "" {
			fmt.Fprintf(&b, " stdin=%q", c.Stdin)
		}
		fmt.Fprintf(&b, " => exit %d, stdout=%q, stderr=%q\n", c.ExitCode, c.Stdout, c.Stderr)
	}
	if previousFailure != "" {
		b.WriteString("\nThe previous attempt failed the recorded behavior. Test output:\n")
		b.WriteString(previousFailure)
		b.WriteString("\nFix rewrite.go so every case passes.\n")
	}
	return b.String()
}

// quotedList renders strings as Go literals for a generated []string{...}.
func quotedList(items []string) string {
	q := make([]string, 0, len(items))
	for _, it := range items {
		q = append(q, strconv.Quote(it))
	}
	return strings.Join(q, ", ")
}

// quotedMap renders a map as Go key: value literals in key order, for a generated map[string]string{...}.
func quotedMap(m map[string]string) string {
	q := make([]string, 0, len(m))
	for _, k := range sortedKeys(m) {
		q = append(q, strconv.Quote(k)+": "+strconv.Quote(m[k]))
	}
	return strings.Join(q, ", ")
}
