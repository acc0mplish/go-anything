// CasesFor returns the recorded HTTP cases that belong to a unit's URL prefix.
func CasesFor(rec domain.AppRecording, prefix string) []domain.AppCase {
	var out []domain.AppCase
	for _, c := range rec.Cases {
		if c.Kind == "http" && strings.HasPrefix(c.Path, prefix) {
			out = append(out, c)
		}
	}
	return out
}

const casesTestTemplate = `package {{.Unit}}

import (
	"net/http/httptest"
	"strings"
	"testing"
)

// TestRecordedBehavior replays the recorded behavior of the original for this unit.
// Generated by go-anything from the app recording. The rewrite must satisfy every case. Answers are
// judged by gaCompareAnswer, the tool's own comparison (ga_answer_test.go, ga_compare_test.go).
func TestRecordedBehavior(t *testing.T) {
	opt := gaCompareOptions{JSONBody: {{.JSONBody}}, FloatTolerance: {{.Tolerance}}, Normalize: []string{ {{.Normalize}} }}
	cases := []struct {
		name     string
		method   string
		path     string
		body     string
		want     gaAnswer
		unstable []string
	}{
{{- range .Cases}}
		{ {{.Name}}, {{.Method}}, {{.Path}}, {{.Body}}, gaAnswer{Kind: "http", Status: {{.Status}}, Body: {{.Response}}, Headers: map[string]string{ {{.Headers}} }}, []string{ {{.Unstable}} } },
{{- end}}
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			req := httptest.NewRequest(c.method, c.path, strings.NewReader(c.body))
			rec := httptest.NewRecorder()
			Handle(rec, req)
			got := gaAnswer{Kind: "http", Status: rec.Code, Body: rec.Body.String(), Headers: map[string]string{}}
			for h := range c.want.Headers {
				got.Headers[h] = rec.Header().Get(h)
			}
			for _, d := range gaCompareAnswer(c.want, got, c.unstable, opt) {
				t.Errorf("%s: want %q, got %q %s", d.What, d.Want, d.Got, d.Detail)
			}
		})
	}
}
`

// CasesTest renders units/<unit>/cases_test.go from the recorded cases of that unit.
func CasesTest(unit string, cases []domain.AppCase, opt domain.CompareOptions) ([]byte, error) {
	if err := ValidUnitName(unit); err != nil {
		return nil, err
	}
	type row struct {
		Name, Method, Path, Body, Headers, Response, Unstable string
		Status                                                int
	}
	var rows []row
	for _, c := range cases {
		rows = append(rows, row{
			Name:     strconv.Quote(c.Name),
			Method:   strconv.Quote(c.Method),
			Path:     strconv.Quote(c.Path),
			Body:     strconv.Quote(c.Body),
			Status:   c.Status,
			Headers:  quotedMap(c.Headers),
			Response: strconv.Quote(c.ResponseBody),
			Unstable: quotedList(c.Unstable),
		})
	}
	t, err := template.New("cases").Parse(casesTestTemplate)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, struct {
		Unit                string
		JSONBody, Tolerance string
		Normalize           string
		Cases               []row
	}{unit, strconv.FormatBool(opt.JSONBody), strconv.FormatFloat(opt.FloatTolerance, 'g', -1, 64), quotedList(opt.Normalize), rows}); err != nil {
		return nil, fmt.Errorf("wire: render cases test: %w", err)
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("wire: cases test does not format: %w", err)
	}
	return formatted, nil
}

// AgentPrompt is the whole brief for the agent that writes a rewrite. It carries the recorded
// behavior and the unit contract, and deliberately not the original's source: the rewrite must be
// written from observed behavior alone (clean room).
func AgentPrompt(unit, prefix string, cases []domain.AppCase, previousFailure string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Write the Go file units/%[1]s/rewrite.go for the unit %[1]q, served under %[2]s.\n\n", unit, prefix)
	b.WriteString("Contract:\n")
	fmt.Fprintf(&b, "- package %s, with exactly this function: func Handle(w http.ResponseWriter, r *http.Request)\n", unit)
	b.WriteString("- Replace the whole file. Do not touch any other file. Use only the standard library.\n")
	b.WriteString("- Do not panic and do not leave placeholders.\n\n")
	b.WriteString("Clean room: you may use ONLY the recorded behavior below. Do not look for, open or copy the\n")
	b.WriteString("original program's source. Implement what the cases show, in general, not just these inputs.\n\n")
	b.WriteString("Recorded behavior (request -> response of the original):\n")
	for _, c := range cases {
		fmt.Fprintf(&b, "- %s %s", c.Method, c.Path)
		if c.Body != "" {
			fmt.Fprintf(&b, " body=%q", c.Body)
		}
		fmt.Fprintf(&b, " => status %d", c.Status)
		if ct := c.Headers["Content-Type"]; ct != "" {
			fmt.Fprintf(&b, ", Content-Type %s", ct)
		}
		fmt.Fprintf(&b, ", body=%q\n", c.ResponseBody)
	}
	if previousFailure != "" {
		b.WriteString("\nThe previous attempt failed the recorded behavior. Test output:\n")
		b.WriteString(previousFailure)
		b.WriteString("\nFix rewrite.go so every case passes.\n")
	}
	return b.String()
}

// CasesForCommand returns the recorded command-line cases that run a unit's command: the first
// argument of each case names it.
func CasesForCommand(rec domain.AppRecording, unit string) []domain.AppCase {
	var out []domain.AppCase
	for _, c := range rec.Cases {
		if c.Kind == "cli" && len(c.Argv) > 0 && c.Argv[0] == unit {
			out = append(out, c)
		}
	}
	return out
}

