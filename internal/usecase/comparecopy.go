package usecase

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"sort"
	"strings"
	"unicode"

	"github.com/go-anything/go-anything/internal/domain"
)

// ComparisonPrefix starts every top-level name of the copied comparison code, so the copy cannot collide
// with a name the rewrite declares in the same package.
const ComparisonPrefix = "ga"

// ComparisonTestFiles returns the answer comparison as test-only files for package pkg, keyed by file
// name. They are mechanical copies of internal/domain/compare.go and answer.go with the package clause
// replaced and each top-level name prefixed, so generated tests apply exactly the tool's rule.
func ComparisonTestFiles(pkg string) (map[string][]byte, error) {
	srcs, err := domain.ComparisonSources()
	if err != nil {
		return nil, fmt.Errorf("wire: comparison sources: %w", err)
	}
	fset := token.NewFileSet()
	files := map[string]*ast.File{}
	top := map[string]bool{}
	for name, src := range srcs {
		f, err := parser.ParseFile(fset, name, src, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("wire: parse %s: %w", name, err)
		}
		files[name] = f
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil {
					top[d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						top[s.Name.Name] = true
					case *ast.ValueSpec:
						for _, n := range s.Names {
							top[n.Name] = true
						}
					}
				}
			}
		}
	}
	out := map[string][]byte{}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		f := files[name]
		f.Name.Name = pkg
		imports := map[string]bool{}
		for _, im := range f.Imports {
			p := strings.Trim(im.Path.Value, `"`)
			imports[p[strings.LastIndex(p, "/")+1:]] = true
		}
		// Field names, composite-literal keys and selector names never refer to a top-level identifier,
		// so they must not be prefixed however they are spelled: a field named like a function (the
		// Normalize field meets the Normalize function) would otherwise be renamed on one side only.
		keep := map[token.Pos]bool{}
		ast.Inspect(f, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.SelectorExpr:
				keep[n.Sel.Pos()] = true
			case *ast.StructType:
				for _, fl := range n.Fields.List {
					for _, id := range fl.Names {
						keep[id.Pos()] = true
					}
				}
			case *ast.KeyValueExpr:
				if id, ok := n.Key.(*ast.Ident); ok {
					keep[id.Pos()] = true
				}
			}
			return true
		})
		ast.Inspect(f, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if x, ok := sel.X.(*ast.Ident); ok && imports[x.Name] {
					return false // strings.Split: the selected name belongs to another package
				}
			}
			if id, ok := n.(*ast.Ident); ok && top[id.Name] && id != f.Name && !keep[id.Pos()] {
				id.Name = prefixed(id.Name)
			}
			return true
		})
		var buf bytes.Buffer
		fmt.Fprintf(&buf, "// Code generated by go-anything from internal/domain/%s. DO NOT EDIT.\n// It is the comparison the tool itself uses, so this test and go-anything judge answers alike.\n\n", name)
		if err := format.Node(&buf, fset, f); err != nil {
			return nil, fmt.Errorf("wire: print %s: %w", name, err)
		}
		out["ga_"+strings.TrimSuffix(name, ".go")+"_test.go"] = buf.Bytes()
	}
	return out, nil
}

func prefixed(name string) string {
	r := []rune(name)
	r[0] = unicode.ToUpper(r[0])
	return ComparisonPrefix + string(r)
}
